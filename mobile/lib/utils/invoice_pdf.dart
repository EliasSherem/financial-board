String invoiceDisplayNumber(InvoiceSummary invoice) {
  final raw = invoice.number.trim();
  if (raw.isEmpty || raw == '#') return '#${invoice.id}';
  return raw.startsWith('#') ? raw : '#$raw';
}

String invoicePdfFilename(InvoiceSummary invoice) {
  final raw = invoiceDisplayNumber(invoice).replaceAll('#', '');
  final cleaned = raw.replaceAll(RegExp(r'[^A-Za-z0-9._-]'), '_');
  final safe = cleaned.isEmpty ? invoice.id.toString() : cleaned;
  return 'FinSight_Invoice_$safe.pdf';
}

String formatInvoiceMoney(num value, String currency) {
  final code = currency.trim().isEmpty ? 'MXN' : currency.toUpperCase();
  final formatter = NumberFormat.currency(
    locale: 'en_US',
    name: code,
    symbol: _currencySymbol(code),
  );
  return formatter.format(value);
}

String _currencySymbol(String currency) {
  switch (currency.toUpperCase()) {
    case 'EUR':
      return 'EUR ';
    case 'GBP':
      return 'GBP ';
    case 'USD':
      return '\$';
    case 'MXN':
      return '\$';
    default:
      return '$currency ';
  }
}

String _formatQuantity(double value) {
  if (value == value.roundToDouble()) {
    return value.toStringAsFixed(0);
  }
  return value.toStringAsFixed(2);
}

Future<Uint8List> buildInvoicePdf(
  BuildContext context,
  InvoiceDetail detail,
  String? senderName,
) async {
  final invoice = detail.invoice;
  final label = invoiceDisplayNumber(invoice);
  final locale = Localizations.localeOf(context).toString();
  final invoiceTitle = I18n.tr(context, 'invoices.invoice');
  final customerTitle = I18n.tr(context, 'invoices.customer');
  final itemsTitle = I18n.tr(context, 'invoices.items');
  final descriptionTitle = I18n.tr(context, 'invoices.description');
  final qtyTitle = I18n.tr(context, 'invoices.qty');
  final unitPriceTitle = I18n.tr(context, 'invoices.unitPrice');
  final amountTitle = I18n.tr(context, 'invoices.amount');
  final subtotalTitle = I18n.tr(context, 'invoices.subtotal');
  final discountTitle = I18n.tr(context, 'invoices.discount');
  final taxTitle = I18n.tr(context, 'invoices.tax');
  final totalTitle = I18n.tr(context, 'invoices.total');
  final dueAmountTitle = I18n.tr(context, 'invoices.dueAmount');
  final sentByTitle = I18n.tr(context, 'invoices.sentBy');
  final logoBytes = await rootBundle.load('assets/finsight-icon.png');
  final regularFontBytes = await rootBundle.load(
    'assets/fonts/NotoSans-Regular.ttf',
  );
  final boldFontBytes = await rootBundle.load('assets/fonts/NotoSans-Bold.ttf');
  final logo = pw.MemoryImage(logoBytes.buffer.asUint8List());
  final regularFont = pw.Font.ttf(regularFontBytes);
  final boldFont = pw.Font.ttf(boldFontBytes);
  final dateFmt = DateFormat('dd/MM/yyyy', locale);
  final notes = (invoice.notes ?? '').trim();
  final safeSenderName = (senderName ?? '').trim();

  String formatMoney(num value) => formatInvoiceMoney(value, invoice.currency);

  final customerLines = <String>[
    invoice.customerName,
    if ((invoice.customerCompany ?? '').trim().isNotEmpty)
      'Company: ${invoice.customerCompany!.trim()}',
    if ((invoice.customerEmail ?? '').trim().isNotEmpty)
      'Email: ${invoice.customerEmail!.trim()}',
    if ((invoice.customerTaxId ?? '').trim().isNotEmpty)
      'Tax ID: ${invoice.customerTaxId!.trim()}',
    if ((invoice.customerAddress ?? '').trim().isNotEmpty)
      'Address: ${invoice.customerAddress!.trim()}',
  ];

  final items =
      detail.items
          .map(
            (item) => [
              item.description,
              _formatQuantity(item.quantity),
              formatMoney(item.unitPrice),
              formatMoney(item.amount),
            ],
          )
          .toList();
  final payments =
      detail.payments
          .map(
            (payment) => [formatYmd(payment.date), formatMoney(payment.amount)],
          )
          .toList();

  final doc = pw.Document();
  final sectionTitle = pw.TextStyle(
    fontSize: 12,
    fontWeight: pw.FontWeight.bold,
  );

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(24),
      theme: pw.ThemeData.withFont(base: regularFont, bold: boldFont),
      footer:
          (pageContext) => pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Generated by FinSight',
                style: const pw.TextStyle(
                  fontSize: 9,
                  color: PdfColors.grey600,
                ),
              ),
              pw.Text(
                'Page ${pageContext.pageNumber} of ${pageContext.pagesCount}',
                style: const pw.TextStyle(
                  fontSize: 9,
                  color: PdfColors.grey600,
                ),
              ),
            ],
          ),
      build:
          (_) => [
            pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Container(
                  width: 42,
                  height: 42,
                  decoration: pw.BoxDecoration(
                    color: PdfColors.blue50,
                    borderRadius: const pw.BorderRadius.all(
                      pw.Radius.circular(10),
                    ),
                  ),
                  child: pw.Center(
                    child: pw.Image(logo, width: 28, height: 28),
                  ),
                ),
                pw.SizedBox(width: 12),
                pw.Expanded(
                  child: pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'FinSight',
                        style: pw.TextStyle(
                          fontSize: 20,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                      pw.SizedBox(height: 2),
                      pw.Text(
                        '$invoiceTitle $label',
                        style: const pw.TextStyle(fontSize: 12),
                      ),
                    ],
                  ),
                ),
                pw.Container(
                  padding: const pw.EdgeInsets.symmetric(
                    horizontal: 10,
                    vertical: 6,
                  ),
                  decoration: pw.BoxDecoration(
                    color:
                        invoice.status.toLowerCase() == 'paid'
                            ? PdfColors.green50
                            : PdfColors.blue50,
                    borderRadius: const pw.BorderRadius.all(
                      pw.Radius.circular(999),
                    ),
                  ),
                  child: pw.Text(
                    invoice.status.toUpperCase(),
                    style: pw.TextStyle(
                      fontSize: 10,
                      fontWeight: pw.FontWeight.bold,
                      color:
                          invoice.status.toLowerCase() == 'paid'
                              ? PdfColors.green800
                              : PdfColors.blue800,
                    ),
                  ),
                ),
              ],
            ),
            pw.SizedBox(height: 18),
            pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Expanded(
                  child: pw.Container(
                    padding: const pw.EdgeInsets.all(14),
                    decoration: pw.BoxDecoration(
                      border: pw.Border.all(color: PdfColors.grey300),
                      borderRadius: const pw.BorderRadius.all(
                        pw.Radius.circular(12),
                      ),
                    ),
                    child: pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.start,
                      children: [
                        pw.Text('Invoice details', style: sectionTitle),
                        pw.SizedBox(height: 10),
                        _pdfKv('Invoice', label),
                        _pdfKv('Date', dateFmt.format(invoice.issueDate)),
                        _pdfKv('Due', dateFmt.format(invoice.dueDate)),
                        _pdfKv('Currency', invoice.currency),
                        if (safeSenderName.isNotEmpty)
                          _pdfKv(sentByTitle, safeSenderName),
                        _pdfKv(totalTitle, formatMoney(invoice.total)),
                        _pdfKv(dueAmountTitle, formatMoney(invoice.amountDue)),
                      ],
                    ),
                  ),
                ),
                pw.SizedBox(width: 12),
                pw.Expanded(
                  child: pw.Container(
                    padding: const pw.EdgeInsets.all(14),
                    decoration: pw.BoxDecoration(
                      border: pw.Border.all(color: PdfColors.grey300),
                      borderRadius: const pw.BorderRadius.all(
                        pw.Radius.circular(12),
                      ),
                    ),
                    child: pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.start,
                      children: [
                        pw.Text(customerTitle, style: sectionTitle),
                        pw.SizedBox(height: 10),
                        ...customerLines.map(
                          (line) => pw.Padding(
                            padding: const pw.EdgeInsets.only(bottom: 4),
                            child: pw.Text(
                              line,
                              style: const pw.TextStyle(fontSize: 10.5),
                            ),
                          ),
                        ),
                      ],
                    ),
                  ),
                ),
              ],
            ),
            pw.SizedBox(height: 18),
            pw.Text(itemsTitle, style: sectionTitle),
            pw.SizedBox(height: 8),
            pw.TableHelper.fromTextArray(
              headers: [
                descriptionTitle,
                qtyTitle,
                unitPriceTitle,
                amountTitle,
              ],
              data: items,
              headerDecoration: const pw.BoxDecoration(
                color: PdfColors.grey200,
              ),
              headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
              cellStyle: const pw.TextStyle(fontSize: 10),
              cellAlignment: pw.Alignment.centerLeft,
              cellAlignments: {
                1: pw.Alignment.centerRight,
                2: pw.Alignment.centerRight,
                3: pw.Alignment.centerRight,
              },
              columnWidths: const {
                0: pw.FlexColumnWidth(3.8),
                1: pw.FlexColumnWidth(1.1),
                2: pw.FlexColumnWidth(1.8),
                3: pw.FlexColumnWidth(1.8),
              },
            ),
            pw.SizedBox(height: 12),
            pw.Align(
              alignment: pw.Alignment.centerRight,
              child: pw.Container(
                width: 230,
                padding: const pw.EdgeInsets.all(12),
                decoration: pw.BoxDecoration(
                  color: PdfColors.grey100,
                  borderRadius: const pw.BorderRadius.all(
                    pw.Radius.circular(12),
                  ),
                ),
                child: pw.Column(
                  children: [
                    _pdfTotalsRow(subtotalTitle, formatMoney(invoice.subtotal)),
                    _pdfTotalsRow(
                      discountTitle,
                      '-${formatMoney(invoice.discount)}',
                    ),
                    _pdfTotalsRow(taxTitle, '+${formatMoney(invoice.tax)}'),
                    pw.Divider(height: 12),
                    _pdfTotalsRow(
                      totalTitle,
                      formatMoney(invoice.total),
                      isBold: true,
                    ),
                    _pdfTotalsRow(
                      dueAmountTitle,
                      formatMoney(invoice.amountDue),
                      isBold: true,
                    ),
                  ],
                ),
              ),
            ),
            if (notes.isNotEmpty) ...[
              pw.SizedBox(height: 18),
              pw.Text('Notes', style: sectionTitle),
              pw.SizedBox(height: 6),
              pw.Container(
                padding: const pw.EdgeInsets.all(12),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: PdfColors.grey300),
                  borderRadius: const pw.BorderRadius.all(
                    pw.Radius.circular(12),
                  ),
                ),
                child: pw.Text(
                  notes,
                  style: const pw.TextStyle(fontSize: 10.5),
                ),
              ),
            ],
            if (payments.isNotEmpty) ...[
              pw.SizedBox(height: 18),
              pw.Text('Payments', style: sectionTitle),
              pw.SizedBox(height: 8),
              pw.TableHelper.fromTextArray(
                headers: ['Date', 'Amount'],
                data: payments,
                headerDecoration: const pw.BoxDecoration(
                  color: PdfColors.grey200,
                ),
                headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                cellStyle: const pw.TextStyle(fontSize: 10),
                cellAlignment: pw.Alignment.centerLeft,
                cellAlignments: {1: pw.Alignment.centerRight},
                columnWidths: const {
                  0: pw.FlexColumnWidth(1.8),
                  1: pw.FlexColumnWidth(1.5),
                },
              ),
            ],
          ],
    ),
  );

  return doc.save();
}

pw.Widget _pdfKv(String label, String value) {
  return pw.Padding(
    padding: const pw.EdgeInsets.only(bottom: 6),
    child: pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          label,
          style: const pw.TextStyle(fontSize: 9.5, color: PdfColors.grey700),
        ),
        pw.SizedBox(height: 2),
        pw.Text(
          value,
          style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold),
        ),
      ],
    ),
  );
}

pw.Widget _pdfTotalsRow(String label, String value, {bool isBold = false}) {
  return pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 2),
    child: pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Text(label, style: const pw.TextStyle(fontSize: 10)),
        pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 10,
            fontWeight: isBold ? pw.FontWeight.bold : pw.FontWeight.normal,
          ),
        ),
      ],
    ),
  );
}
